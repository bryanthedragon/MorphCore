    @Override
    public SoundEvent getHurtSound(LivingEntity target, DamageSource damageSource)
    {
        LivingEntity entity = this.getEntity(target.level());

        try
        {
            Method methodHurtSound = InvokeUtil.getPrivateMethod(entity.getClass(), LivingEntity.class, SoundHandler.GET_HURT_SOUND.getName(), DamageSource.class);
            SoundEvent hurtSound = (SoundEvent) methodHurtSound.invoke(entity, damageSource);
            if (hurtSound == null)
            {
                hurtSound = SoundHandler.NO_SOUND;
            }
            return hurtSound;
        }
        catch (Exception e)
        {
            e.printStackTrace();
        }

        return null;
    }

